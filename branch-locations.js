/** Exact provider + branch + city match only; never substitute headquarters. */
export function branchLocation(quote) {
  if (!quote || typeof quote.sourceId !== 'string' || typeof quote.branch !== 'string') return null;
  const key = `${quote.sourceId}:${quote.branch}`;
  if (!Object.hasOwn(BRANCH_LOCATIONS, key)) return null;
  const location = BRANCH_LOCATIONS[key];
  return quote.city === location.city ? { ...location } : null;
}
