const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({...(process.env.BROWSER_EXECUTABLE ? {executablePath:process.env.BROWSER_EXECUTABLE} : {}),headless:true,args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 let fail=false,delay=false;
 await page.route('https://r.jina.ai/**',async route=>{
  if(!route.request().url().includes('nortecambios')) return route.fulfill({status:503,body:'Unavailable'});
  const currency=route.request().url().split('/').pop();
  if(delay&&currency==='EUR') await new Promise(r=>setTimeout(r,500));
  if(fail) return route.fulfill({status:503,body:'Unavailable'});
  return route.fulfill({status:200,contentType:'text/plain',body:fs.readFileSync(`${__dirname}/fixtures/norte-${currency.toLowerCase()}-2026-10-20.md`,'utf8')});
 });
 await page.goto('http://127.0.0.1:8000');
 await page.waitForFunction(()=>!document.querySelector('#fetchBtn').disabled);
 assert.match(await page.locator('#result').textContent(),/565[.]?000/);
 assert.equal(await page.locator('.quote .branch').textContent(),'Asunción');
 await page.selectOption('#operation','buy');
 assert.match(await page.locator('#result').textContent(),/575[.]?000/);
 await page.fill('#amount','0'); assert.equal(await page.locator('#result').textContent(),'—');
 await page.fill('#amount','100');
 await page.selectOption('#currencySelect','ARS');
 await page.waitForFunction(()=>document.querySelector('#result').textContent.includes('380'));
 delay=true;
 await page.selectOption('#currencySelect','EUR'); await page.selectOption('#currencySelect','BRL');
 await page.waitForFunction(()=>document.querySelector('#result').textContent.includes('115.500'));
 await page.waitForTimeout(650);
 assert.match(await page.locator('#calculationDetail').textContent(),/BRL/);
 fail=true; await page.click('#fetchBtn');
 await page.waitForFunction(()=>document.querySelector('#status').classList.contains('error'));
 assert.equal(await page.locator('.previous').count(),1);
 assert.equal(await page.locator('#result').textContent(),'—');
 await page.selectOption('#currencySelect','EUR');
 await page.waitForFunction(()=>document.querySelector('#status').classList.contains('error'));
 assert.equal(await page.locator('.quote').count(),0);
 assert.match(await page.locator('#quotes').textContent(),/Sin cotizaciones/);
 fail=false; await page.selectOption('#currencySelect','USD');
 await page.waitForFunction(()=>!document.querySelector('#fetchBtn').disabled);
 await page.selectOption('#citySelect','Ciudad del Este');
 await page.waitForFunction(()=>!document.querySelector('#fetchBtn').disabled);
 assert.equal(await page.locator('.quote .branch').textContent(),'Ciudad del Este');
 assert.match(await page.locator('#result').textContent(),/573[.]?000/);
 await page.screenshot({path:'/tmp/cambio-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'/tmp/cambio-mobile.png',fullPage:true});
 await page.setViewportSize({width:320,height:700});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS browser: buy/sell, amount validation, 4 currencies, overlapping requests, all-fail, previous session data, recovery, mobile 390/320, no JS errors');
})().catch(e=>{console.error(e);process.exit(1)});
